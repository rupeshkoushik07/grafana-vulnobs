#!/usr/bin/env bash
# Render the Tanka environment to plain YAML for Flux.
#
# Flux reconciles deploy/flux/apps/vulnobs/ from Git, so the rendered manifests
# are committed. Rerun this after changing deploy/tanka/ and commit the result;
# the flux.yml workflow fails if the committed output is stale.
#
# Usage: tools/export-flux-manifests.sh        (needs `tk` on PATH)
set -euo pipefail
export LC_ALL=C  # stable file order

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
env_dir="environments/default"
out="$root/deploy/flux/apps/vulnobs"
header="# Generated by tools/export-flux-manifests.sh from deploy/tanka/$env_dir. Do not edit."

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

(cd "$root/deploy/tanka" && tk export "$tmp/out" "$env_dir" \
  --format '{{.kind | lower}}-{{.metadata.name}}' >/dev/null)
rm -f "$tmp/out/manifest.json"

# Secrets are created out of band (see deploy/flux/README.md) and must never
# end up in Git.
if grep -lx 'kind: Secret' "$tmp"/out/*.yaml; then
  echo "error: the environment renders a Secret; refusing to export it" >&2
  exit 1
fi

rm -f "$out"/*.yaml
mkdir -p "$out"
{
  echo "$header"
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  for f in "$tmp"/out/*.yaml; do
    name="$(basename "$f")"
    { echo "$header"; cat "$f"; } > "$out/$name"
    echo "  - $name"
  done
} > "$out/kustomization.yaml"

echo "Exported $(($(ls "$out" | wc -l) - 1)) manifests to ${out#"$root"/}"
